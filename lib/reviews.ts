export function getReviewStories(locale: Locale = "ko"): ReviewStory[] {
  if (locale === "ko") return reviewStories;

  const translatedEarlierStories = earlierStories.map(story => {
    const translation = reviewTranslationsZhTW[story.id];
    return {
      ...story,
      title: translation.title,
      topic: translation.topic,
      clientName: translation.clientName,
      messages: story.messages.map((message, index) => ({
        ...message,
        text: translation.messages[index],
        time: message.time?.replace("오전", "上午").replace("오후", "下午"),
      })),
    };
  });
  return [translatedEarlierStories[0], ...getCaseStories(locale), ...translatedEarlierStories.slice(1)];
}

export function getFeaturedReviews(locale: Locale = "ko"): ReviewStory[] {
  const stories = getReviewStories(locale);
  return featuredIds.map(id => stories.find(story => story.id === id)!);
}



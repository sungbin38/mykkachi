// Categorize by the Korean source, so translated stories keep the same filters.
export function getReviewCategory(id: number): Exclude<ReviewCategory, "all"> {
  const topic = reviewStories.find(story => story.id === id)?.topic ?? "";
  if (/자녀/.test(topic)) return "family";
  if (/^학업|편입|전공|적성 찾기|적성과 시험/.test(topic)) return "study";
  if (/^애정|^연애|^결혼|^재회/.test(topic)) return "love";
  if (/^재물|창업/.test(topic)) return "wealth";
  if (/^건강/.test(topic)) return "health";
  return "career";
}

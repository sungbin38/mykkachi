export function getCaseStories(locale: Locale = "ko"): ReviewStory[] {
  return consultationCases.map(({ id, ...entry }) => {
    const copy = entry[locale];
    return {
      id,
      title: copy.title,
      topic: copy.topic,
      clientName: entry.clientName,
      kind: "case",
      theme: "classic",
      messages: [
        { role: "client", text: copy.question, preview: true },
        { role: "teacher", text: copy.advice, preview: true },
        ...(copy.reply ? [{ role: "client" as const, text: copy.reply, preview: true }] : []),
      ],
    };
  });
}
